#!/bin/bash

# 1. Проверяем, является ли день праздничным (Пример для январских и майских праздников)
# Формат даты: день-месяц (DD-MM)
CURRENT_DATE=$(date +%d-%m)
PRASDNIKI=("01-01" "02-01" "03-01" "04-01" "05-01" "06-01" "07-01" "08-01" "23-02" "08-03" "01-05" "09-05" "12-06" "04-11")

for day in "${PRASDNIKI[@]}"; do
    if [ "$CURRENT_DATE" == "$day" ]; then
        # Если праздничный день — доступ разрешен всем
        exit 0
    fi
done

# 2. Проверяем, выходной ли сегодня день (Суббота или Воскресенье)
WEEKDAY=$(date +%a)
if [ "$WEEKDAY" == "Sat" ] || [ "$WEEKDAY" == "Sun" ]; then
    # Проверяем, входит ли подключающийся пользователь ($PAM_USER) в группу admin
    if getent group admin | grep -qw "$PAM_USER"; then
        # Администраторам в выходной можно
        exit 0
    else
        # Всем остальным доступ запрещен
        exit 1
    fi
else
    # В будние дни доступ разрешен всем
    exit 0
fi
